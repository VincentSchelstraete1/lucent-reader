// Run with an existing Playwright installation (NODE_PATH when it is external).
// No accounts, uploaded documents, or provider calls are used by this preview.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = process.env.BASE_URL || 'http://127.0.0.1:5173'
const output = process.env.EVIDENCE_DIR || '.tmp/flythrough/acceptance'
fs.mkdirSync(output, { recursive: true })
const errors = [], evidence = []

;(async () => {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || undefined, headless: true, args: process.env.BROWSER_CHANNEL ? ['--enable-webgl'] : ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(base)
    await page.locator('canvas[data-camera]').waitFor()
    async function at(p, name) {
      await page.evaluate(p => scrollTo(0, (document.querySelector('main').offsetHeight - innerHeight) * p), p)
      await page.waitForFunction(p => Math.abs(Number(document.querySelector('canvas')?.dataset.progress) - p) < .002, p, { timeout: 60000 })
      await page.screenshot({ path: path.join(output, name + '.png') })
      evidence.push({ name, p, camera: await page.locator('canvas').getAttribute('data-camera') })
      console.log(name)
    }
    await at(0, '01-pure-alpine-opening')
    assert.equal(await page.getByRole('heading', { name: 'Turn any material into understanding.' }).count(), 0)
    await at(.13, '02-descending-pages')
    await at(.18, '03-assembled-pages')
    const before = await page.evaluate(() => scrollY)
    await page.getByRole('button', { name: 'Next source page' }).click()
    await page.getByText('2 / 5 · Simplify', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => scrollY), before)
    await page.getByRole('button', { name: 'Previous source page' }).click()
    await page.getByText('1 / 5 · Source material', { exact: true }).waitFor()
    await at(.22, '04-pages-falling-into-fog')
    await at(.38, '05-calm-lake')
    await at(.50, '06-paper-architecture-arriving')
    await at(.55, '07-first-feature-discovery')
    await at(.64, '08-interactive-product-in-world')
    const demo = page.getByRole('region', { name: 'Interactive Lucent preview', exact: true })
    const cameraScroll = await page.evaluate(() => scrollY)
    await demo.getByRole('button', { name: 'It repairs every damaged protein by itself.' }).click()
    await demo.getByText(/Notice the two highlighted steps/).waitFor()
    assert.equal(await page.evaluate(() => scrollY), cameraScroll, 'answering must not move the camera')
    await page.screenshot({ path: path.join(output, '09-wrong-answer-teaching.png') })
    await demo.getByRole('button', { name: 'Explain differently', exact: true }).click()
    await demo.getByText(/Think of a smoke alarm/).waitFor()
    await demo.getByRole('button', { name: 'Why does this matter?', exact: true }).click()
    await demo.getByText(/A damaged protein can interfere/).waitFor()
    assert.equal(await demo.getByText(/Think of a smoke alarm/).count(), 0)
    await demo.getByRole('button', { name: 'It connects detection to a protective response.' }).click()
    assert.equal(await page.evaluate(() => scrollY), cameraScroll, 'Ask and guided success must not move the camera')
    await demo.getByRole('button', { name: 'Expand Control signals in intracellular quality control', exact: true }).click()
    const dialog = demo.getByRole('dialog')
    await dialog.waitFor()
    await page.keyboard.press('Shift+Tab')
    assert(await page.evaluate(() => !!document.activeElement?.closest('[role="dialog"]')), 'expanded visual contains keyboard focus')
    await page.screenshot({ path: path.join(output, '10-expanded-visual.png') })
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => scrollY), cameraScroll, 'closing expansion preserves the camera')
    await at(.695, '11-passing-beside-product')
    await at(.755, '12-next-feature-discovery')
    await at(.83, '13-unravelling-exit')
    await at(1, '14-final-overlook')
    await at(.64, '15-return-to-preserved-demo')
    assert.equal(await demo.getByRole('button', { name: 'It connects detection to a protective response.' }).getAttribute('aria-pressed'), 'true')
    await page.goto(base + '/#learn-in-action')
    await page.waitForFunction(() => Math.abs(Number(document.querySelector('canvas')?.dataset.progress) - .64) < .003, undefined, { timeout: 60000 })
    evidence.push({ name: 'preview-deep-link', passed: true })
    await page.evaluate(() => document.querySelector('canvas').getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
    await page.locator('main[data-static-story="true"]').waitFor()
    assert.equal(await page.locator('canvas').count(), 0)
    evidence.push({ name: 'WebGL-context-loss-fallback', passed: true })

    for (const [name, options] of [
      ['mobile', { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }],
      ['reduced-motion', { viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' }],
    ]) {
      const context = await browser.newContext(options), fallback = await context.newPage()
      fallback.on('pageerror', e => errors.push(e.message))
      await fallback.goto(base)
      await fallback.locator('main[data-static-story="true"]').waitFor()
      assert.equal(await fallback.locator('canvas').count(), 0)
      assert(await fallback.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      await fallback.getByRole('button', { name: 'Next source page' }).click()
      await fallback.getByText('2 / 5 · Simplify', { exact: true }).waitFor()
      await fallback.getByRole('link', { name: 'Explore Lucent', exact: true }).click()
      const open = fallback.getByRole('button', { name: 'Open interactive preview', exact: true })
      if (await open.count()) await open.click()
      await fallback.getByRole('button', { name: 'It repairs every damaged protein by itself.' }).click()
      await fallback.getByText(/Notice the two highlighted steps/).waitFor()
      await fallback.screenshot({ path: path.join(output, name + '.png') })
      evidence.push({ name, passed: true })
      await context.close()
    }
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({ evidence, errors }, null, 2))
    console.log('PASS: desktop journey, embedded interaction, deep link, mobile and reduced motion')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
